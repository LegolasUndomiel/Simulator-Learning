"""Generate pinned OpenCourant source/dependency manifests from CMake Ninja output.

This is a maintenance tool only. The Xmake build consumes the generated Lua
manifest and never reads CMake output.
"""

from __future__ import annotations

import argparse
import pathlib
import re


def parse_component(root: pathlib.Path, component: str, target: str):
    oc = root / "Simulators" / "opencourant"
    build = root / "build" / "simulators" / "opencourant" / f"build-{component}"
    ninja = (build / "build.ninja").read_text(errors="replace")
    dyndep = (build / "CMakeFiles" / f"{target}.dir" / "Fortran.dd").read_text(errors="replace")

    fortran: list[str] = []
    produces: dict[str, set[str]] = {}
    requires: dict[str, set[str]] = {}
    for line in dyndep.splitlines():
        if not line.startswith("build "):
            continue
        normalized = line.replace("\\\\", "/")
        match = re.search(
            rf"CMakeFiles/{re.escape(target)}\.dir/(.+?\.(?:F|F90|f90))\.obj"
            r"(?:\s+\|\s+(.+?))?: dyndep(?:\s+\|\s+(.+))?$",
            normalized,
        )
        if not match:
            raise RuntimeError(f"unparsed Fortran.dd line: {line}")
        encoded = match.group(1)
        marker = "opencourant/"
        if marker in encoded:
            encoded = encoded.split(marker, 1)[1]
        else:
            encoded = component + "/" + encoded
        source = encoded
        fortran.append(source)
        produces[source] = set(re.findall(r"([^/\s]+\.mod)", match.group(2) or ""))
        requires[source] = set(re.findall(r"([^/\s]+\.mod)", match.group(3) or ""))

    providers = {module: source for source, modules in produces.items() for module in modules}
    dependencies = {
        source: {
            providers[module]
            for module in requires[source]
            if module in providers and providers[module] != source
        }
        for source in fortran
    }
    remaining = set(fortran)
    levels: list[list[str]] = []
    while remaining:
        ready = sorted(source for source in remaining if not dependencies[source] & remaining)
        if not ready:
            raise RuntimeError(f"cyclic Fortran dependencies: {sorted(remaining)}")
        levels.append(ready)
        remaining.difference_update(ready)

    c_sources: list[str] = []
    cxx_sources: list[str] = []
    for line in ninja.splitlines():
        if not line.startswith("build ") or "COMPILER__" not in line:
            continue
        match = re.search(r": (CXX|C)_COMPILER__\S+\s+(.+?)(?:\s+\|\|.*)?$", line)
        if not match:
            continue
        source = match.group(2).replace("D$:", "D:").replace("\\", "/")
        relative = pathlib.PureWindowsPath(source).relative_to(
            pathlib.PureWindowsPath(str(oc))
        ).as_posix()
        (cxx_sources if match.group(1) == "CXX" else c_sources).append(relative)

    return levels, sorted(c_sources), sorted(cxx_sources)


def lua_list(values: list[str], indent: str) -> str:
    return "\n".join(f'{indent}"{value}",' for value in values)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("root", type=pathlib.Path)
    parser.add_argument("output", type=pathlib.Path)
    args = parser.parse_args()

    components = {}
    for component, target in (("starter", "starter_win64"), ("engine", "engine_win64")):
        components[component] = parse_component(args.root.resolve(), component, target)

    lines = [
        "-- Generated by generate_manifest.py from the pinned official Ninja build.",
        "-- Runtime Xmake builds do not read CMake/Ninja output.",
        "OC_IFX_MANIFEST = {",
    ]
    for component, (levels, c_sources, cxx_sources) in components.items():
        lines.append(f"    {component} = {{")
        lines.append("        fortran_levels = {")
        for level in levels:
            lines.append("            {")
            lines.append(lua_list(level, "                "))
            lines.append("            },")
        lines.append("        },")
        lines.append("        c_sources = {")
        lines.append(lua_list(c_sources, "            "))
        lines.append("        },")
        lines.append("        cxx_sources = {")
        lines.append(lua_list(cxx_sources, "            "))
        lines.append("        },")
        lines.append("    },")
    lines.append("}")
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")

    for component, (levels, c_sources, cxx_sources) in components.items():
        print(
            component,
            f"Fortran={sum(map(len, levels))}",
            f"levels={len(levels)}",
            f"level_sizes={[len(level) for level in levels]}",
            f"C={len(c_sources)}",
            f"CXX={len(cxx_sources)}",
        )


if __name__ == "__main__":
    main()
